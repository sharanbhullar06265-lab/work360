export function getInitialCMS(kind: string, fallback: any[]): any[] {
  if (!kind || kind === "bridge") return fallback;
  const seen = new Set<string>();
  const out: Record<string, string>[] = [];
  for (const row of CMS_ROWS) {
    if (row["rw-row"] !== kind) continue;
    const isSite = kind === "site";
    const o: Record<string, string> = {
      "rw-row": String(row["rw-row"] ?? ""),
      slug: String(row.slug ?? ""),
      f1: String(isSite ? SITE_CONFIG.brandName : (row.f1 ?? "")),
      f2: String(isSite ? SITE_CONFIG.tagline : (row.f2 ?? "")),
      f3: String(isSite ? SITE_CONFIG.blurb : (row.f3 ?? "")),
      f4: String(isSite ? SITE_CONFIG.email : (row.f4 ?? "")),
      f5: String(isSite ? SITE_CONFIG.phone : (row.f5 ?? "")),
      f6: String(isSite ? SITE_CONFIG.bookingLink : (row.f6 ?? "")),
      f7: String(isSite ? SITE_CONFIG.city : (row.f7 ?? "")),
      f8: String(isSite ? SITE_CONFIG.timezone : (row.f8 ?? "")),
      f9: String(isSite ? SITE_CONFIG.rating : (row.f9 ?? "")),
      f10: String(isSite ? SITE_CONFIG.reviewsCount : (row.f10 ?? "")),
      f11: String(isSite ? SITE_CONFIG.socials : (row.f11 ?? "")),
      f12: String(isSite ? SITE_CONFIG.announcement : (row.f12 ?? "")),
      f13: String(isSite ? SITE_CONFIG.brandsGrown : (row.f13 ?? "")),
      f14: String(row.f14 ?? ""),
      f15: String(row.f15 ?? ""),
      f16: String(row.f16 ?? ""),
      n1: String(row.n1 ?? "0"),
      n2: String(row.n2 ?? "0"),
      img: String(row.img ?? ""),
      img2: String(row.img2 ?? ""),
    };
    const key = o.slug || JSON.stringify(o);
    if (seen.has(key)) continue;
    seen.add(key);
    out.push(o);
  }
  out.sort((a, b) => (parseFloat(a.n1) || 0) - (parseFloat(b.n1) || 0));
  return out;
}

